from io import BytesIO
from datetime import datetime

from reportlab.lib import colors
from reportlab.lib.enums import TA_CENTER
from reportlab.lib.styles import getSampleStyleSheet
from reportlab.lib.units import inch
from reportlab.platypus import (
    SimpleDocTemplate,
    Paragraph,
    Spacer,
    Table,
    TableStyle,
    PageBreak,
)

from reportlab.graphics.shapes import Drawing
from reportlab.graphics.charts.barcharts import VerticalBarChart
from reportlab.graphics.charts.textlabels import Label

from reportlab.pdfbase import pdfmetrics
from reportlab.pdfbase.ttfonts import TTFont

try:
    pdfmetrics.registerFont(
        TTFont(
            "Helvetica",
            "Helvetica.ttf"
        )
    )
except Exception:
    pass


def generate_interview_pdf(session):

    """
    Generates a professional interview report PDF.

    Returns:
        BytesIO
    """

    buffer = BytesIO()

    doc = SimpleDocTemplate(

        buffer,

        rightMargin=40,

        leftMargin=40,

        topMargin=40,

        bottomMargin=40,

    )

    styles = getSampleStyleSheet()

    title_style = styles["Title"]
    title_style.alignment = TA_CENTER
    title_style.textColor = colors.HexColor("#16a34a")

    heading_style = styles["Heading1"]
    heading_style.textColor = colors.HexColor("#15803d")

    subheading_style = styles["Heading2"]
    subheading_style.textColor = colors.HexColor("#166534")

    normal_style = styles["BodyText"]

    

    story = []

    # ==========================================
    # TITLE
    # ==========================================

    story.append(
        Paragraph(
            "<font size=22><b>Nova AI Career Assistant</b></font>",
            title_style,
        )
    )

    story.append(
        Paragraph(
            "<font size=16>Professional Interview Assessment Report</font>",
            normal_style,
        )
    )

    story.append(Spacer(1, 0.3 * inch))

    story.append(
        Paragraph(
            f"<b>Candidate:</b> {session.user.get_full_name() or session.user.username}",
            normal_style,
        )
    )

    story.append(
        Paragraph(
            f"<b>Date:</b> {datetime.now().strftime('%d %B %Y')}",
            normal_style,
        )
    )

    story.append(
        Paragraph(
            f"<b>Generated by:</b> Nova AI Career Assistant",
            normal_style,
        )
    )

    story.append(Spacer(1, 0.25 * inch))

    # ==========================================
    # BASIC INFO
    # ==========================================

    info = [

        ["Company", session.company],

        ["Role", session.job_role],

        ["Interview Type", session.get_interview_type_display()],

        ["Experience", session.get_experience_level_display()],

        ["Difficulty", session.get_difficulty_display()],

        ["Overall Score", f"{session.overall_score:.1f}"],

        ["Recommendation", session.recommendation],

    ]

    table = Table(

        info,

        colWidths=[150, 320],

    )

    table.setStyle(

        TableStyle([

            ("BACKGROUND", (0, 0), (0, -1), colors.HexColor("#166534")),

            ("TEXTCOLOR", (0, 0), (0, -1), colors.white),

            ("FONTNAME", (0, 0), (-1, -1), "Helvetica"),

            ("BOTTOMPADDING", (0, 0), (-1, -1), 8),

            ("TOPPADDING", (0, 0), (-1, -1), 8),

            ("GRID", (0, 0), (-1, -1), 0.5, colors.grey),

            ("BACKGROUND", (1, 0), (1, -1), colors.whitesmoke),

        ])

    )

    story.append(table)

    story.append(Spacer(1, 0.3 * inch))

    # ==========================================
    # PERFORMANCE
    # ==========================================

    story.append(

        Paragraph(

            "<b>Performance Breakdown</b>",

             subheading_style

        )

    )

    report = session.report

    performance = [

        ["Communication", f"{report.communication:.1f}%"],

        ["Technical", f"{report.technical:.1f}%"],

        ["Confidence", f"{report.confidence:.1f}%"],

        ["Problem Solving", f"{report.problem_solving:.1f}%"],

        ["Culture Fit", f"{report.culture_fit:.1f}%"],

    ]

    perf_table = Table(

        performance,

        colWidths=[220, 120],

    )

    perf_table.setStyle(

        TableStyle([

            ("GRID", (0, 0), (-1, -1), 0.5, colors.grey),

            ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#dcfce7")),

            ("BOTTOMPADDING", (0, 0), (-1, -1), 8),

        ])

    )

    story.append(perf_table)

    story.append(Spacer(1, 0.3 * inch))


    drawing = Drawing(420, 220)

    chart = VerticalBarChart()

    chart.x = 50
    chart.y = 40

    chart.width = 300
    chart.height = 140

    chart.data = [[
        report.communication,
        report.technical,
        report.confidence,
        report.problem_solving,
        report.culture_fit,
    ]]

    chart.categoryAxis.categoryNames = [
        "Comm",
        "Tech",
        "Conf",
        "Problem",
        "Culture",
    ]

    chart.valueAxis.valueMin = 0
    chart.valueAxis.valueMax = 100
    chart.valueAxis.valueStep = 20

    drawing.add(chart)

    title = Label()
    title.setOrigin(120, 190)
    title.setText("Performance Overview")

    drawing.add(title)

    story.append(drawing)
    story.append(Spacer(1, 0.35 * inch))

#Report Overall Score
    story.append(
    Paragraph(
        f"""
        <para align="center">
        <font size="24" color="#16a34a">
        <b>{session.overall_score:.1f}/100</b>
        </font>
        </para>
        """,
        normal_style,
    )
)

    story.append(
        Paragraph(
            '<para align="center"><b>Overall Interview Score</b></para>',
            normal_style,
        )
    )

    story.append(Spacer(1, 0.3 * inch))

    # ==========================================
    # SUMMARY
    # ==========================================

    story.append(

        Paragraph(

            "<b>AI Summary</b>",

             subheading_style

        )

    )

    story.append(

        Paragraph(

            report.summary,

            styles["BodyText"],

        )

    )

    story.append(Spacer(1, 0.3 * inch))

    # ==========================================
    # STRENGTHS
    # ==========================================

    story.append(

        Paragraph(

            "<b>Strengths</b>",

             subheading_style

        )

    )

    for item in report.strengths:

        story.append(
            Paragraph(
                f"<font color='green'>✓</font> {item}",
                normal_style,
            )
        )
    story.append(Spacer(1, 0.2 * inch))

    # ==========================================
    # WEAKNESSES
    # ==========================================

    story.append(

        Paragraph(

            "<b>Areas for Improvement</b>",

            styles["Heading2"],

        )

    )

    for item in report.weaknesses:

        story.append(
            Paragraph(
                f"<font color='red'>•</font> {item}",
                normal_style,
            )
        )

    story.append(Spacer(1, 0.3 * inch))

    # ==========================================
    # QUESTIONS
    # ==========================================

    story.append(

        Paragraph(

            "<b>Interview Review</b>",

            styles["Heading1"],

        )

    )

    for question in session.questions.all():

        story.append(

            Paragraph(

                f"<b>Question {question.question_number}</b>",

                styles["Heading3"],

            )

        )

        story.append(

            Paragraph(

                question.question,

                styles["BodyText"],

            )

        )

        if hasattr(question, "answer"):

            answer = question.answer

            story.append(

                Paragraph(

                    "<b>Candidate Answer</b>",

                    styles["Heading4"],

                )

            )

            story.append(

                Paragraph(

                    answer.answer,

                    styles["BodyText"],

                )

            )

            story.append(

                Paragraph(

                    "<b>AI Feedback</b>",

                    styles["Heading4"],

                )

            )

            story.append(

                Paragraph(

                    answer.feedback,

                    styles["BodyText"],

                )

            )

            story.append(

                Paragraph(

                    f"<b>Score:</b> {answer.overall_score}",

                    styles["BodyText"],

                )

            )

        story.append(Spacer(1, 0.25 * inch))


        story.append(Spacer(1, 0.5 * inch))

#Footer
    story.append(Spacer(1, 0.4 * inch))

    story.append(
        Paragraph(
            """
            <para align="center">
            <font size="8" color="grey">
            Generated by Nova AI Career Assistant<br/>
            Confidential • For Candidate Use Only
            </font>
            </para>
            """,
            normal_style,
        )
    )

    doc.build(story)

    buffer.seek(0)

    return buffer

